-- PARRAINAGE HAYEVA — programme ambassadeurs (prime de 20 € par nouveau
-- client éligible, versement à partir de 200 € de solde disponible).
--
-- S'appuie sur l'existant (referral_codes, referrals, referral_events,
-- referral_settings, wallet_* pour le crédit de bienvenue du filleul) et
-- ajoute :
--   * referral_rewards           : UNE prime par parrainage (jamais plus),
--                                  cycle EN ATTENTE → VALIDÉE / NON ÉLIGIBLE ;
--   * referral_payout_requests   : demandes de versement (aucun virement
--                                  automatique — contrôle par l'administration) ;
--   * referral_ledger            : registre financier append-only ;
--   * referral_notifications     : notifications du parrain (dédupliquées).
--
-- Règle unique, appliquée exclusivement côté serveur :
--   NOUVEAU CLIENT + CODE PARRAIN + INTERVENTION TERMINÉE
--   + PAIEMENT CONFIRMÉ (facture PAYÉE, net des remboursements) >= seuil
--   = prime pour le parrain.
-- Une réservation seule ne crédite jamais rien. Montants en centimes
-- entiers (integer), jamais de flottant. Tous les paramètres (prime, seuil
-- d'éligibilité, seuil de versement, activations) sont centralisés dans
-- referral_settings.
--
-- Sécurité : aucune écriture directe possible pour anon/authenticated sur
-- les nouvelles tables (RLS sans policy d'écriture + REVOKE). Le parrain ne
-- lit ses données QUE via get_my_ambassador() (SECURITY DEFINER), qui
-- n'expose aucune donnée personnelle du filleul (référence anonyme
-- « Client #NNNN » uniquement).

-- ---------------------------------------------------------------------
-- 1) Configuration centralisée
-- ---------------------------------------------------------------------
alter table public.referral_settings
  add column if not exists min_eligible_paid_cents integer not null default 10000,
  add column if not exists min_payout_cents integer not null default 20000,
  add column if not exists ambassador_public_enabled boolean not null default false,
  add column if not exists payouts_enabled boolean not null default false;
alter table public.referral_settings add constraint referral_settings_amounts_check
  check (referrer_reward_cents >= 0 and referee_reward_cents >= 0
         and min_eligible_paid_cents > 0 and min_payout_cents > 0);
update public.referral_settings set referrer_reward_cents = 2000, min_eligible_paid_cents = 10000, min_payout_cents = 20000 where id;

-- ---------------------------------------------------------------------
-- 2) Remboursements de facture (montant final réellement payé)
-- ---------------------------------------------------------------------
alter table public.invoices
  add column if not exists refunded_cents integer not null default 0,
  add column if not exists refunded_at timestamptz;
alter table public.invoices add constraint invoices_refunded_cents_check
  check (refunded_cents >= 0 and (total_cents is null or refunded_cents <= total_cents));

create or replace function public.protect_invoice_amount_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not (is_admin() or auth.role() = 'service_role') then
    new.status := old.status;
    new.total_cents := old.total_cents;
    new.refunded_cents := old.refunded_cents;
    new.refunded_at := old.refunded_at;
    new.paid_at := old.paid_at;
  end if;
  return new;
end;
$$;

