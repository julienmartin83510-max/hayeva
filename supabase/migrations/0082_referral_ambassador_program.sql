create table if not exists public.referral_payout_requests (
  id uuid primary key default gen_random_uuid(),
  public_no bigint generated by default as identity (start with 1001) unique,
  referrer_client_id uuid not null references public.clients(id),
  amount_cents integer not null check (amount_cents > 0),
  status text not null default 'REQUESTED' check (status in ('REQUESTED', 'REVIEWING', 'APPROVED', 'PAID', 'REFUSED')),
  requested_at timestamptz not null default now(),
  reviewed_at timestamptz,
  approved_at timestamptz,
  paid_at timestamptz,
  refused_at timestamptz,
  refusal_reason text,
  admin_note text,
  payment_reference text,
  processed_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
-- Une seule demande active par parrain : deux demandes simultanées sont
