-- Validation manuelle : uniquement lorsque l'intervention est TERMINÉE et
-- que l'administrateur confirme le montant réellement payé (>= seuil).
create or replace function public.admin_validate_referral_reward(p_reward_id uuid, p_paid_cents integer, p_note text default null)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare w referral_rewards%rowtype; s referral_settings%rowtype; v_booking uuid; v_ins int;
begin
  if not is_admin() then raise exception 'Accès réservé à l''administration.'; end if;
  select * into s from referral_settings where id;
  select * into w from referral_rewards where id = p_reward_id for update;
  if not found then raise exception 'Prime introuvable.'; end if;
  if w.status = 'VALIDATED' then return 'ALREADY_VALIDATED'; end if;
  if w.status not in ('PENDING', 'REVIEW') then raise exception 'Cette prime n''est plus validable (statut %).', w.status; end if;
  if coalesce(p_paid_cents, 0) < s.min_eligible_paid_cents then
    raise exception 'Montant payé inférieur au seuil de % : aucune prime.', referral_euros(s.min_eligible_paid_cents);
  end if;
  if w.booking_id is not null and exists (select 1 from bookings where id = w.booking_id and status = 'COMPLETED') then
    v_booking := w.booking_id;
  else
    select x.id into v_booking from bookings x join services sv on sv.id = x.service_id
     where x.client_id in (select id from clients where id = w.referee_client_id or merged_into = w.referee_client_id)
       and x.status = 'COMPLETED' and coalesce(sv.referral_eligible, false)
     order by x.date, x.start_time limit 1;
  end if;
  if v_booking is null then raise exception 'Aucune intervention terminée pour ce filleul : validation impossible.'; end if;
  insert into referral_ledger (referrer_client_id, reward_id, entry_type, amount_cents, detail, created_by)
  values (w.referrer_client_id, w.id, 'reward_validated', w.amount_cents,
          jsonb_build_object('booking_id', v_booking, 'paid_amount_cents', p_paid_cents, 'source', 'admin', 'note', p_note), auth.uid())
  on conflict do nothing;
  get diagnostics v_ins = row_count;
  if v_ins = 0 then return 'ALREADY_VALIDATED'; end if;
  update referral_rewards set status = 'VALIDATED', status_code = 'ADMIN_VALIDATED', status_reason = nullif(trim(coalesce(p_note, '')), ''),
         booking_id = v_booking, paid_amount_cents = p_paid_cents, validation_source = 'admin',
         validated_at = now(), validated_by = auth.uid(), updated_at = now()
   where id = w.id;
  perform _referral_after_validation(w.id);
  return 'VALIDATED';
end;
$$;

create or replace function public.admin_reject_referral_reward(p_reward_id uuid, p_reason text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare w referral_rewards%rowtype; v_reason text := coalesce(nullif(trim(p_reason), ''), 'Refusé par l''administration');
begin
  if not is_admin() then raise exception 'Accès réservé à l''administration.'; end if;
  select * into w from referral_rewards where id = p_reward_id for update;
  if not found then raise exception 'Prime introuvable.'; end if;
  if w.status = 'VALIDATED' then
    if w.payout_id is not null and _referral_detach_from_payout(w.id, v_reason) = 'PAID' then
      raise exception 'Prime déjà versée : régularisation à traiter manuellement.';
    end if;
    update referral_rewards set status = 'CANCELLED', status_code = 'ADMIN_CANCELLED', status_reason = v_reason,
           cancelled_at = now(), updated_at = now() where id = w.id;
    insert into referral_ledger (referrer_client_id, reward_id, entry_type, amount_cents, detail, created_by)
    values (w.referrer_client_id, w.id, 'reward_cancelled', -w.amount_cents, jsonb_build_object('reason', v_reason, 'by', 'admin'), auth.uid())
    on conflict do nothing;
  else
    update referral_rewards set status = 'REJECTED', status_code = 'ADMIN_REJECTED', status_reason = v_reason, updated_at = now() where id = w.id;
  end if;
  update referrals set status = 'INELIGIBLE', status_reason = v_reason, updated_at = now() where id = w.referral_id;
  insert into referral_events (referral_id, event, detail) values (w.referral_id, 'ADMIN_REJECTED', jsonb_build_object('reason', v_reason, 'by', auth.uid()));
  return 'REJECTED';
end;
$$;

create or replace function public.admin_set_referral_payout_status(p_payout_id uuid, p_status text, p_note text default null, p_payment_reference text default null)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare p referral_payout_requests%rowtype; v_entry text;
begin
  if not is_admin() then raise exception 'Accès réservé à l''administration.'; end if;
  select * into p from referral_payout_requests where id = p_payout_id for update;
  if not found then raise exception 'Demande introuvable.'; end if;
  if p.status = p_status then return p.status; end if;
  if not ((p.status = 'REQUESTED' and p_status in ('REVIEWING', 'APPROVED', 'REFUSED'))
       or (p.status = 'REVIEWING' and p_status in ('APPROVED', 'REFUSED'))
       or (p.status = 'APPROVED' and p_status in ('PAID', 'REFUSED'))) then
    raise exception 'Transition impossible : % → %.', p.status, p_status;
  end if;
  if p_status = 'PAID' and exists (select 1 from referral_rewards where payout_id = p.id and (status <> 'VALIDATED' or clawback_alert)) then
    raise exception 'Une prime de cette demande n''est plus valide : vérification requise.';
  end if;
  update referral_payout_requests set status = p_status,
         reviewed_at = case when p_status = 'REVIEWING' then now() else reviewed_at end,
         approved_at = case when p_status = 'APPROVED' then now() else approved_at end,
         paid_at = case when p_status = 'PAID' then now() else paid_at end,
         refused_at = case when p_status = 'REFUSED' then now() else refused_at end,
         refusal_reason = case when p_status = 'REFUSED' then nullif(trim(coalesce(p_note, '')), '') else refusal_reason end,
         admin_note = case when p_status <> 'REFUSED' and nullif(trim(coalesce(p_note, '')), '') is not null then concat_ws(' | ', admin_note, p_note) else admin_note end,
         payment_reference = coalesce(nullif(trim(coalesce(p_payment_reference, '')), ''), payment_reference),
         processed_by = auth.uid(), updated_at = now()
   where id = p.id;
  -- Refus : les primes redeviennent disponibles.
  if p_status = 'REFUSED' then
    update referral_rewards set payout_id = null, updated_at = now() where payout_id = p.id;
  end if;
  v_entry := 'payout_' || lower(p_status);
  insert into referral_ledger (referrer_client_id, payout_id, entry_type, amount_cents, detail, created_by)
  values (p.referrer_client_id, p.id, v_entry, p.amount_cents, jsonb_build_object('note', p_note, 'payment_reference', p_payment_reference), auth.uid())
  on conflict do nothing;
  perform referral_notify_client(p.referrer_client_id, 'payout_' || lower(p_status),
    case p_status when 'PAID' then 'Versement effectué' when 'APPROVED' then 'Versement approuvé' when 'REFUSED' then 'Demande de versement refusée' else 'Demande de versement en vérification' end,
    case p_status when 'PAID' then 'Votre versement de ' || referral_euros(p.amount_cents) || ' a été effectué.'
                  when 'APPROVED' then 'Votre demande de versement de ' || referral_euros(p.amount_cents) || ' a été approuvée.'
                  when 'REFUSED' then 'Votre demande de versement n''a pas pu être acceptée. Les montants concernés restent sur votre solde.'
                  else 'Votre demande de versement est en cours de vérification.' end,
    'payout_' || lower(p_status) || ':' || p.id);
  return p_status;
end;
$$;

