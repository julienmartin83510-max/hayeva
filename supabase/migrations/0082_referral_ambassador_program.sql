  on public.referral_payout_requests (referrer_client_id)
  where status in ('REQUESTED', 'REVIEWING', 'APPROVED');

create table if not exists public.referral_rewards (
  id uuid primary key default gen_random_uuid(),
  referral_id uuid not null unique references public.referrals(id),
  referrer_client_id uuid not null references public.clients(id),
  referee_client_id uuid not null references public.clients(id),
  booking_id uuid references public.bookings(id),
  amount_cents integer not null check (amount_cents > 0),
  paid_amount_cents integer check (paid_amount_cents >= 0),
  status text not null default 'PENDING' check (status in ('PENDING', 'REVIEW', 'VALIDATED', 'REJECTED', 'CANCELLED')),
  status_code text not null default 'NO_BOOKING',
  status_reason text,
  review_flags text[] not null default '{}',
  validation_source text check (validation_source in ('auto_invoice', 'admin')),
  validated_at timestamptz,
  validated_by uuid,
  cancelled_at timestamptz,
  payout_id uuid references public.referral_payout_requests(id),
  clawback_alert boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (referrer_client_id <> referee_client_id),
  check (status <> 'VALIDATED' or (validated_at is not null and paid_amount_cents is not null and booking_id is not null)),
  check (payout_id is null or status = 'VALIDATED')
);
-- Une intervention ne peut générer qu'UNE prime validée.
create unique index if not exists referral_rewards_booking_validated_uidx
  on public.referral_rewards (booking_id) where status = 'VALIDATED';
create index if not exists referral_rewards_referrer_idx on public.referral_rewards (referrer_client_id, status);
create index if not exists referral_rewards_referee_idx on public.referral_rewards (referee_client_id);
create index if not exists referral_rewards_payout_idx on public.referral_rewards (payout_id);

create table if not exists public.referral_ledger (
  id uuid primary key default gen_random_uuid(),
  referrer_client_id uuid not null references public.clients(id),
  reward_id uuid references public.referral_rewards(id),
  payout_id uuid references public.referral_payout_requests(id),
  entry_type text not null check (entry_type in (
    'reward_pending', 'reward_validated', 'reward_cancelled', 'reward_clawback_alert',
    'payout_requested', 'payout_reviewing', 'payout_approved', 'payout_paid', 'payout_refused', 'payout_adjusted')),
  amount_cents integer not null default 0,
  detail jsonb not null default '{}'::jsonb,
  created_by uuid,
  created_at timestamptz not null default now()
);
-- Idempotence financière : jamais deux validations / deux annulations de la
-- même prime, jamais deux fois la même étape pour une même demande.
create unique index if not exists referral_ledger_reward_once_uidx
  on public.referral_ledger (reward_id, entry_type)
  where reward_id is not null and entry_type in ('reward_pending', 'reward_validated', 'reward_cancelled', 'reward_clawback_alert');
create unique index if not exists referral_ledger_payout_once_uidx
  on public.referral_ledger (payout_id, entry_type)
  where payout_id is not null and entry_type in ('payout_requested', 'payout_reviewing', 'payout_approved', 'payout_paid', 'payout_refused');
create index if not exists referral_ledger_referrer_idx on public.referral_ledger (referrer_client_id, created_at desc);

