create or replace function public.generate_referral_code_for(p_client uuid)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare v_base text; v text; i int := 0;
begin
  select left(regexp_replace(upper(translate(coalesce(first_name, ''),
           'àâäáãåçéèêëíìîïñóòôöõúùûüýÿÀÂÄÁÃÅÇÉÈÊËÍÌÎÏÑÓÒÔÖÕÚÙÛÜÝ',
           'aaaaaaceeeeiiiinooooouuuuyyAAAAAACEEEEIIIINOOOOOUUUUY')), '[^A-Z]', '', 'g'), 8)
    into v_base from clients where id = p_client;
  if coalesce(length(v_base), 0) >= 3 then
    loop
      i := i + 1;
      v := v_base || (10 + floor(random() * 90))::int::text;
      exit when not exists (select 1 from referral_codes where code = v);
      if i > 20 then exit; end if;
    end loop;
    if i <= 20 then return v; end if;
  end if;
  return generate_referral_code();
end;
$$;
revoke all on function public.generate_referral_code_for(uuid) from public, anon, authenticated;

create or replace function public.get_my_referral_code()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare v_client uuid; v_code text;
begin
  v_client := public.ensure_my_client();
  select code into v_code from referral_codes where client_id = v_client;
  if v_code is null then
    loop
      begin
        insert into referral_codes (client_id, code) values (v_client, public.generate_referral_code_for(v_client)) returning code into v_code;
        exit;
      exception when unique_violation then
        select code into v_code from referral_codes where client_id = v_client;
        exit when v_code is not null;
      end;
    end loop;
  end if;
  return v_code;
end;
$$;

create or replace function public.set_my_referral_code(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare v_client uuid; v_code text := upper(regexp_replace(coalesce(p_code, ''), '\s', '', 'g'));
begin
  v_client := public.ensure_my_client();
  if v_code !~ '^[A-Z0-9]{6,12}$' or v_code !~ '[A-Z]' then
    return jsonb_build_object('ok', false, 'error', 'FORMAT');
  end if;
  if exists (select 1 from referrals where referrer_client_id = v_client) then
    return jsonb_build_object('ok', false, 'error', 'CODE_DEJA_UTILISE');
  end if;
  if exists (select 1 from referral_codes where code = v_code and client_id <> v_client)
     or exists (select 1 from referrals where code_used = v_code) then
    return jsonb_build_object('ok', false, 'error', 'CODE_INDISPONIBLE');
  end if;
  begin
    insert into referral_codes (client_id, code) values (v_client, v_code)
    on conflict (client_id) do update set code = excluded.code;
  exception when unique_violation then
    return jsonb_build_object('ok', false, 'error', 'CODE_INDISPONIBLE');
  end;
  return jsonb_build_object('ok', true, 'code', v_code);
end;
$$;

