create or replace function public.referral_euros(p_cents integer)
returns text
language sql
immutable
as $$
  select case when p_cents % 100 = 0 then (p_cents / 100)::text || ' €'
              else replace(to_char(p_cents / 100.0, 'FM999999990D00'), '.', ',') || ' €' end;
$$;

