insert into public.referral_rewards (referral_id, referrer_client_id, referee_client_id, amount_cents)
select r.id, r.referrer_client_id, r.referee_client_id, (select referrer_reward_cents from public.referral_settings where id)
  from public.referrals r
 where r.status = 'PENDING' and (select referrer_reward_cents from public.referral_settings where id) > 0
on conflict (referral_id) do nothing;
insert into public.referral_ledger (referrer_client_id, reward_id, entry_type, amount_cents, detail)
select w.referrer_client_id, w.id, 'reward_pending', w.amount_cents, '{"backfill": true}'::jsonb from public.referral_rewards w
on conflict do nothing;
select public.referral_evaluate_reward(id) from public.referral_rewards;
